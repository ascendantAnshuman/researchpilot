"""Tests for Markdown/PDF export."""

from __future__ import annotations

from collections.abc import Iterator

import httpx
import pymupdf
import pytest

from app.agents.graph import run_research
from app.config import Settings
from app.schemas import ResearchReport
from app.services import export
from app.services.export import export_filename, pdf_fonts, report_to_markdown, report_to_pdf
from app.services.vector_store import VectorStore
from tests.builders import make_context

QUESTION = "What are recent methods for reducing hallucination in RAG systems?"


@pytest.fixture()
async def report(test_settings: Settings, vector_store: VectorStore, http_client: httpx.AsyncClient) -> ResearchReport:
    """A complete report from the offline pipeline."""
    return await run_research(QUESTION, context=make_context(test_settings, vector_store, http_client))


@pytest.fixture()
def no_unicode_fonts(monkeypatch: pytest.MonkeyPatch) -> Iterator[None]:
    """Pretend no TrueType font is installed (forces the Helvetica fallback)."""
    monkeypatch.setattr(export, "FONT_CANDIDATES", ())
    pdf_fonts.cache_clear()
    yield
    pdf_fonts.cache_clear()


def pdf_text(content: bytes) -> str:
    """All text in a PDF."""
    with pymupdf.open(stream=content, filetype="pdf") as document:
        return " ".join(page.get_text() for page in document)


def test_markdown_export_is_the_report_markdown(report: ResearchReport) -> None:
    """The Markdown download is exactly the stored Markdown, UTF-8 encoded."""
    assert report_to_markdown(report) == report.markdown.encode("utf-8")


def test_pdf_contains_all_parts_of_the_report(report: ResearchReport) -> None:
    """Title, sections, table, verification and references all appear."""
    text = pdf_text(report_to_pdf(report))

    for expected in ("Review: hallucination in RAG", "Executive summary", "Methods", "Comparison of key papers",
                     "Verification", "References", "Generated by ResearchPilot", "Page 1"):
        assert expected in text


def test_pdf_handles_markup_characters_and_unicode(report: ResearchReport) -> None:
    """Characters that are special in ReportLab markup or outside Latin-1 do not break the export."""
    tricky = report.model_copy(
        update={"title": "Scores <0.5 & recall ≥ 90% for α-RAG → better", "executive_summary": "Precision < recall & F1."}
    )

    text = pdf_text(report_to_pdf(tricky))

    assert "Scores <0.5 & recall" in text
    if pdf_fonts().unicode:
        assert "≥ 90% for α-RAG → better" in text


def test_pdf_falls_back_to_helvetica_without_unicode_fonts(report: ResearchReport, no_unicode_fonts: None) -> None:
    """Without a TTF font the PDF still renders; unsupported characters are transliterated."""
    tricky = report.model_copy(update={"title": "Café α-RAG"})

    content = report_to_pdf(tricky)

    assert pdf_fonts().regular == "Helvetica"
    assert "Café ?-RAG" in pdf_text(content)


def test_to_latin1_transliteration() -> None:
    """Latin-1 accents survive, other accents are stripped, symbols become '?'."""
    assert export.to_latin1("Café Erdős α ≥ ﬁne") == "Café Erdos ? ? fine"


def test_export_filename(report: ResearchReport) -> None:
    """File names are lower-case slugs with the right extension."""
    assert export_filename(report, "pdf") == "review-hallucination-in-rag.pdf"
    assert export_filename(report.model_copy(update={"title": "???"}), "md") == "research-report.md"
